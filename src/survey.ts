const q = (
  id: string,
  section: number,
  label: string,
  labels: string[],
  extra: Partial<Question> = {},
): Question => ({
  id,
  section,
  label,
  type: "single",
  options: labels.map((label, i) => ({ value: `v${i + 1}`, label })),
  optional: true,
  multiple: false,
  maxSelections: 1,
  exclusiveOptions: labels.flatMap((label, i) =>
    /^(أفضل عدم الإجابة|لا أعرف|لا يوجد ضغط|لا أرى عوائق|لم نحتج إلى تغيير)/.test(
      label,
    )
      ? [`v${i + 1}`]
      : [],
  ),
  storage: `responses.answers.${id}`,
  aggregate: true,
  ...extra,
});
