export const visible = (q: Question, answers: Record<string, unknown>) =>
  !q.condition ||
  q.condition.values.includes(String(answers[q.condition.question]));
export function answerSchema(q: Question) {
  if (q.type === "text") return z.string().trim().min(1).max(q.maxLength!);
  const option = z.enum(q.options.map((o) => o.value) as [string, ...string[]]);
  return q.multiple
    ? z
        .array(option)
        .min(1)
        .max(q.maxSelections)
        .refine((v) => new Set(v).size === v.length, "duplicate options")
        .refine(
          (v) =>
            v.length === 1 || !v.some((x) => q.exclusiveOptions.includes(x)),
          "exclusive option",
        )
    : option;
}
export const answersSchema = z
  .record(z.string(), z.unknown())
  .superRefine((answers, ctx) => {
    for (const [id, value] of Object.entries(answers)) {
      const q = questions.find((q) => q.id === id);
      if (
        !q ||
        !visible(q, answers) ||
        !answerSchema(q).safeParse(value).success
      )
        ctx.addIssue({
          code: "custom",
          path: [id],
          message: "إجابة غير صالحة أو سؤال غير ظاهر",
        });
    }
  });
export const submissionSchema = z
  .object({
    requestId: z.uuid(),
    answers: answersSchema,
    consent: z.literal(true),
    botToken: z.string().min(1).max(2048),
  })
  .strict();
export const cleanAnswers = (answers: Record<string, unknown>) =>
  Object.fromEntries(
    Object.entries(answers).filter(([id, v]) => {
      const q = questions.find((q) => q.id === id);
      return (
        q &&
        visible(q, answers) &&
        !(typeof v === "string" && !v.trim()) &&
        (!Array.isArray(v) || v.length > 0)
      );
    }),
  );
